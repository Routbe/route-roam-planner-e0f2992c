#!/usr/bin/env python3
"""Regenerates the Poseidon parameters of rout-zk from first principles.

Port of the reference generator generate_parameters_grain.sage (Grassi,
Khovratovich, Rechberger, Roy, Schofnegger; hadeshash, commit on master,
https://extgit.iaik.tugraz.at/krypto/hadeshash/-/blob/master/code/generate_parameters_grain.sage)
for the instance used by rout-zk:

    GF(p), p = BLS12-381 scalar field order, x^5 S-box, n = 255, t = 3,
    R_F = 8, R_P = 57   (reference: poseidonperm_x5_255_3.sage)

The Grain LFSR output is fully determined by these parameters, so anybody can
reproduce every constant. Usage:

    python3 tools/poseidon_params.py check   # compare with tests/fixtures/poseidon/x5_255_3.json
    python3 tools/poseidon_params.py rust    # print src/poseidon_constants.rs

`check` also runs the permutation on the reference input [0, 1, 2] and compares
it with the published output.
"""
import json
import os
import sys

P = 0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001
FIELD, SBOX, N_BITS, T, R_F, R_P = 1, 0, 255, 3, 8, 57
HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURE = os.path.join(HERE, "..", "tests", "fixtures", "poseidon", "x5_255_3.json")


def grain():
    bits = []
    for value, width in ((FIELD, 2), (SBOX, 4), (N_BITS, 12), (T, 12), (R_F, 10), (R_P, 10)):
        bits += [int(c) for c in bin(value)[2:].zfill(width)]
    bits += [1] * 30
    assert len(bits) == 80

    def step():
        b = bits[62] ^ bits[51] ^ bits[38] ^ bits[23] ^ bits[13] ^ bits[0]
        bits.pop(0)
        bits.append(b)
        return b

    for _ in range(160):
        step()
    while True:
        b = step()
        while b == 0:
            step()
            b = step()
        yield step()


GEN = grain()


def rand_bits(n):
    v = 0
    for _ in range(n):
        v = (v << 1) | next(GEN)
    return v


def params():
    rc = []
    for _ in range((R_F + R_P) * T):
        r = rand_bits(N_BITS)
        while r >= P:
            r = rand_bits(N_BITS)
        rc.append(r)
    # First Cauchy-matrix candidate (the reference then runs its algorithms
    # 1-3 against infinitely long subspace trails and retries on failure; the
    # published matrix equals this first candidate, which `check` asserts).
    while True:
        xs_ys = [rand_bits(N_BITS) % P for _ in range(2 * T)]
        while len(set(xs_ys)) != len(xs_ys):
            xs_ys = [rand_bits(N_BITS) % P for _ in range(2 * T)]
        xs, ys = xs_ys[:T], xs_ys[T:]
        if all((x + y) % P for x in xs for y in ys):
            mds = [[pow((x + y) % P, P - 2, P) for y in ys] for x in xs]
            return rc, mds


def perm(state, rc, mds):
    s = list(state)
    k = 0
    for rnd in range(R_F + R_P):
        s = [(s[i] + rc[k + i]) % P for i in range(T)]
        k += T
        full = rnd < R_F // 2 or rnd >= R_F // 2 + R_P
        s = [pow(x, 5, P) for x in s] if full else [pow(s[0], 5, P)] + s[1:]
        s = [sum(mds[i][j] * s[j] for j in range(T)) % P for i in range(T)]
    return s


def limbs(v):
    return ", ".join("0x%016x" % ((v >> (64 * i)) & (2**64 - 1)) for i in range(4))


def main():
    rc, mds = params()
    if sys.argv[1:] == ["check"]:
        with open(FIXTURE) as f:
            fx = json.load(f)
        assert [int(x, 16) for x in fx["round_constants"]] == rc, "round constants differ"
        assert [[int(x, 16) for x in row] for row in fx["mds"]] == mds, "MDS differs"
        for v in fx["vectors"]:
            out = perm([int(x, 16) for x in v["input"]], rc, mds)
            assert out == [int(x, 16) for x in v["output"]], "permutation vector differs"
        print("ok: %d round constants, 3x3 MDS and %d vector(s) match" % (len(rc), len(fx["vectors"])))
    elif sys.argv[1:] == ["rust"]:
        print("//! GENERATED by tools/poseidon_params.py (Grain LFSR, x^5, n = 255, t = 3,")
        print("//! R_F = 8, R_P = 57 over the BLS12-381 scalar field). Do not edit by hand;")
        print("//! tests/poseidon.rs compares every value with the reference fixture.")
        print("use bls12_381::Scalar;\n")
        print("pub const ROUND_CONSTANTS: [Scalar; %d] = [" % len(rc))
        for r in rc:
            print("    Scalar::from_raw([%s])," % limbs(r))
        print("];\n")
        print("pub const MDS: [[Scalar; 3]; 3] = [")
        for row in mds:
            print("    [" + ", ".join("Scalar::from_raw([%s])" % limbs(x) for x in row) + "],")
        print("];")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
